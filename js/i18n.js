let currentLang = localStorage.getItem('pb_system_lang') || 'en';

function t(key) {
    if (I18N_DICTIONARY[currentLang] && I18N_DICTIONARY[currentLang][key] !== undefined) {
        return I18N_DICTIONARY[currentLang][key];
    }
    if (I18N_DICTIONARY['en'] && I18N_DICTIONARY['en'][key] !== undefined) {
        return I18N_DICTIONARY['en'][key];
    }
    return key;
}

function setLanguage(lang) {
    if (!I18N_DICTIONARY[lang]) return;
    currentLang = lang;
    localStorage.setItem('pb_system_lang', lang);
    document.documentElement.lang = lang;

    // Apply translations to all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerText = t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', t(key));
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.setAttribute('title', t(key));
    });

    // Update active state of language switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('bg-blue-600', 'text-white', 'shadow');
            btn.classList.remove('bg-slate-100', 'text-slate-600');
        } else {
            btn.classList.remove('bg-blue-600', 'text-white', 'shadow');
            btn.classList.add('bg-slate-100', 'text-slate-600');
        }
    });

    // Re-render current tab to refresh table columns, badges, and headers
    if (typeof updateDynamicLanguageElements === 'function') {
        updateDynamicLanguageElements();
    } else if (typeof activeUser !== 'undefined' && activeUser && typeof renderCurrentTab === 'function') {
        renderCurrentTab();
    }
}
